// Reviewed translation of the 0054 catalog, not a general PostgreSQL converter.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const catalogUrl = new URL('../schema/legacy-postgres.json', import.meta.url);
const outputUrl = new URL('../crates/yoink-storage/migrations-turso/0002_application.sql', import.meta.url);
const catalog = JSON.parse(await readFile(catalogUrl, 'utf8'));
if (catalog.revision !== '0054_restore_stats_latest_view' || catalog.tables.length !== 42) {
  throw new Error('Review the changed source catalog before generating a native schema');
}
const identifier = (name) => {
  if (!/^[a-z_][a-z_0-9]*$/.test(name)) throw new Error(`Unsupported identifier: ${name}`);
  return `"${name}"`;
};
const now = "(CAST(unixepoch('subsec') * 1000000 AS INTEGER))";
const externallyAssignedIds = new Set(['users', 'groups']);
// All these nonunique indexes have an unfiltered PK/unique/composite replacement.
const redundant = new Set([
  'idx_sgm_chat_user', 'idx_stats_un_user_date', 'idx_user_permissions_user',
  'ix_inbox_teams_owner_user_id', 'idx_stats_msg_chat',
  'idx_stats_reactions_user_chat', 'idx_stats_msg_chat_msgid',
]);
const additional = [
  ['cookies_user_fk', 'cookies', ['user_id']],
  ['inbox_categories_parent_fk', 'inbox_categories', ['parent_id']],
  ['inbox_gh_folders_parent_fk', 'inbox_gh_folders', ['parent_id']],
  ['inbox_item_categories_actor_fk', 'inbox_item_categories', ['attached_by_user_id']],
  ['inbox_item_to_star_star_fk', 'inbox_item_to_star', ['gh_star_id']],
  ['inbox_item_to_star_folder_fk', 'inbox_item_to_star', ['folder_id']],
  ['user_group_policies_group_user', 'user_group_policies', ['group_id', 'user_id']],
];

function defaultValue(column) {
  const value = column.default_value;
  if (!value || column.generated || column.sequence) return '';
  if (value === 'now()') return ` DEFAULT ${now}`;
  if (value === 'true' || value === 'false') return ` DEFAULT ${value === 'true' ? 1 : 0}`;
  if (/^-?\d+$/.test(value)) return ` DEFAULT ${value}`;
  const literal = value.match(/^('(?:[^']|'')*')::(?:character varying|bigint|json|jsonb|userrole)$/);
  if (literal) return ` DEFAULT ${literal[1]}`;
  throw new Error(`Unreviewed default for ${column.name}: ${value}`);
}

function columnSql(table, column, primary) {
  const name = identifier(column.name);
  const internalId = column.name === 'id' && column.sequence && !externallyAssignedIds.has(table.name);
  const types = { int4: 'INTEGER', int8: 'INTEGER', bool: 'INTEGER', float8: 'REAL', timestamptz: 'INTEGER', varchar: 'TEXT', text: 'TEXT', json: 'TEXT', jsonb: 'TEXT', userrole: 'TEXT' };
  let type = types[column.udt];
  if (!type) throw new Error(`Unreviewed type ${table.name}.${column.name}: ${column.udt}`);
  if (externallyAssignedIds.has(table.name) && column.name === 'id') type = 'INT';
  let sql = `${name} ${type}`;
  if (internalId) {
    if (primary !== 'PRIMARY KEY (id)') throw new Error(`Unexpected identity key: ${table.name}`);
    sql += ' PRIMARY KEY AUTOINCREMENT';
  }
  if (column.not_null) sql += ' NOT NULL';
  sql += defaultValue(column);
  if (column.udt === 'int4') sql += ` CHECK (${name} BETWEEN -2147483648 AND 2147483647)`;
  if (column.udt === 'bool') sql += ` CHECK (${name} IN (0, 1))`;
  if (column.udt === 'json' || column.udt === 'jsonb') sql += ` CHECK (${name} IS NULL OR json_valid(${name}))`;
  if (column.udt === 'userrole') {
    if (JSON.stringify(catalog.enums.userrole) !== JSON.stringify(['owner', 'admin', 'moderator', 'user', 'restricted', 'banned'])) throw new Error('Unreviewed role enum');
    sql += ` CHECK (${name} IN ('owner', 'admin', 'moderator', 'user', 'restricted', 'banned'))`;
  }
  const length = column.type.match(/^character varying\((\d+)\)$/);
  if (length) sql += ` CHECK (length(${name}) <= ${length[1]})`;
  return sql;
}

const statements = [
  '-- Generated by scripts/native-schema.mjs from the reviewed 0054 catalog.',
  '-- All source entities are retained except Alembic bookkeeping and derived PG tsvector.',
  '-- Timestamps are signed UTC microseconds. JSON remains validated TEXT.',
  '-- Category normalized_name is an explicit, preserved Unicode key, not SQLite lower(name).',
  '-- See schema/README.md for uniqueness preflight, retained grant sources and index decisions.',
  '',
];
let tableCount = 0;
let omittedIndexes = 0;
for (const table of catalog.tables) {
  if (table.name === 'alembic_version') continue;
  identifier(table.name);
  const primary = table.constraints.find(c => c.kind === 'p')?.definition;
  const columns = table.columns.filter(c => !(table.name === 'stats_messages' && c.name === 'text_search'));
  const internalId = columns.some(c => c.name === 'id' && c.sequence) && !externallyAssignedIds.has(table.name);
  const definitions = columns.map(c => columnSql(table, c, primary));
  for (const constraint of table.constraints) {
    if (constraint.kind === 'p' && internalId) continue;
    if (!['p', 'u', 'f', 'c'].includes(constraint.kind)) throw new Error(`Unsupported constraint: ${constraint.name}`);
    definitions.push(constraint.definition);
  }
  if (table.name === 'stats_messages') definitions.push('UNIQUE (chat_id, message_id)');
  statements.push(`CREATE TABLE ${identifier(table.name)} (\n    ${definitions.join(',\n    ')}\n) STRICT;`, '');
  tableCount++;

  const constraintKeys = new Set(table.constraints.filter(c => c.kind === 'p' || c.kind === 'u').map(c => c.definition.replace(/^(?:PRIMARY KEY|UNIQUE) /, '')));
  for (const original of table.indexes) {
    const match = original.match(/^CREATE (UNIQUE )?INDEX ([a-z_0-9]+) ON public\.([a-z_0-9]+) USING (btree|gin) (\([a-z_0-9", ]+\))( WHERE .+)?$/);
    if (!match || match[3] !== table.name) throw new Error(`Unreviewed index: ${original}`);
    const [, unique, name, , method, keys, predicate = ''] = match;
    if (name === 'idx_stats_msg_fts' && method === 'gin' && keys === '(text_search)') {
      omittedIndexes++;
      continue;
    }
    if (method !== 'btree') throw new Error(`Unreviewed index method: ${name}`);
    if ((unique && !predicate && constraintKeys.has(keys)) || redundant.has(name)) {
      omittedIndexes++;
      continue;
    }
    // Restricted source predicates have no functions, collations or PG casts.
    if (predicate && !/^ WHERE \([a-z_]+ (?:IS NOT NULL|= false)\)$/.test(predicate)) throw new Error(`Unreviewed index predicate: ${name}`);
    statements.push(`CREATE ${unique ?? ''}INDEX ${identifier(name)} ON ${identifier(table.name)} ${keys}${predicate.replace(/\bfalse\b/g, '0')};`);
  }
  statements.push('');
}
for (const [name, table, columns] of additional) {
  statements.push(`CREATE INDEX ${identifier(name)} ON ${identifier(table)} (${columns.map(identifier).join(', ')});`);
}
statements.push('CREATE UNIQUE INDEX thread_policies_default_unique ON thread_policies(group_id) WHERE thread_id IS NULL;', '');
statements.push('CREATE VIEW stats_user_latest_name AS', 'SELECT current.user_id, current.username, current.display_name, current.date', 'FROM stats_user_names AS current', 'WHERE NOT EXISTS (SELECT 1 FROM stats_user_names AS newer', '                  WHERE newer.user_id = current.user_id AND newer.date > current.date);', '');
const generated = statements.join('\n');
if (process.argv.includes('--check')) {
  if (await readFile(outputUrl, 'utf8') !== generated) throw new Error('Native schema differs: run just generate-schema and review the diff');
} else {
  await writeFile(outputUrl, generated, { flag: 'w' });
}
console.log(`${tableCount} application tables, ${omittedIndexes} source indexes replaced/omitted: ${fileURLToPath(outputUrl)}`);
